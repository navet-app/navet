import { readFile, writeFile } from 'node:fs/promises';
import { transformWithOxc } from 'vite';

// These modules deliberately use only type imports and runtime-portable built-ins.
// Keep generated artifacts committed so NJS deployment needs no Node runtime.
const entries = [
  ['chore-occurrence-policy', 'njs'],
  ['chore-calendar-policy', 'njs'],
  ['chore-progress-policy', 'njs'],
  ['chore-recurrence-policy', 'njs'],
  ['chore-storage-policy', 'njs'],
  ['resource-host-policy', 'njs'],
  ['credential-policy', 'shared'],
  ['record-safety', 'shared'],
];

for (const [name, directory] of entries) {
  const source = new URL('../packages/core/src/' + name + '.ts', import.meta.url);
  const output = new URL('../docker/' + directory + '/' + name + '.js', import.meta.url);
  const result = await transformWithOxc(await readFile(source, 'utf8'), name + '.ts', {
    target: 'es2015',
  });
  if (/^import /m.test(result.code)) {
    throw new Error('Packaged runtime policy must have no runtime imports: ' + name);
  }
  // Native njs accepts default exports only. Restrict this portable module surface
  // to exported functions so new unsupported syntax fails the build explicitly.
  const exports = [];
  const code = result.code.replace(/^export function (\w+)/gm, (_match, name) => {
    exports.push(name);
    return 'function ' + name;
  });
  if (/^\s*export\b/m.test(code) || /\b(?:const|let|var)\s+[\[{]/.test(code) || /\bfor\s*\([^)]*\bof\b/.test(code) || /\bObject\.hasOwn\(/.test(code)) {
    throw new Error('Runtime policy contains syntax or built-ins unsupported by NJS: ' + name);
  }
  const generated =
    '// Generated by scripts/build-runtime-policies.mjs. Edit packages/core/src/' +
    name + '.ts.\n' + code + '\nexport default { ' + exports.join(', ') + ' };\n';
  if (process.argv.includes('--check')) {
    const existing = await readFile(output, 'utf8').catch(() => '');
    if (existing !== generated) {
      console.error(name + ' artifact is stale. Run node scripts/build-runtime-policies.mjs.');
      process.exitCode = 1;
    }
  } else {
    await writeFile(output, generated);
  }
}
